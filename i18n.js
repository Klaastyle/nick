let currentLang = 'en';

function setLang(lang) {
  currentLang = lang;
  document.documentElement.lang = lang;
  const t = translations[lang];
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t && t[key] !== undefined) el.textContent = t[key];
  });
  // Sync TOTS els botons de llengua (topbar + navbar)
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.remove('active'));
  ['btn-' + lang, 'nav-btn-' + lang].forEach(id => {
    const el = document.getElementById(id);
    if (el) el.classList.add('active');
  });
  const descs = {
    en: 'Freelance translator and proofreader of Spanish and Catalan into English. 15+ years of experience.',
    es: 'Traductor y corrector freelance del español y catalán al inglés. Más de 15 años de experiencia.',
    ca: "Traductor i corrector freelance de l'espanyol i català a l'anglès. Més de 15 anys d'experiència."
  };
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.content = descs[lang];
}
